#pragma once
#include <functional>
#include <string>

// ===========================================================================
// 候选分诊 —— 决定"哪些候选值得问用户"
// ===========================================================================
//
// 用户需求原话：
//   「可以用 ds 作为基础知识库，遇到有陌生知识的地方再提问吗」
//
// 【先纠正一个认识，它决定设计对不对】
// 用模型当"基础知识库"，**不是**让它回答"TV 是什么" —— 我们不需要那个答案，
// 也永远不该把它的答案写进知识库。它在这里的角色只有一个：
//
//     **判断这个词是不是人人皆知 → 从而决定要不要占用用户的注意力。**
//
// 也就是说：模型的输出是一个**判决**（问 / 不问），不是一个**事实**。
//
// ---------------------------------------------------------------------------
// 【这条边界是硬约束，不是风格问题】
// ---------------------------------------------------------------------------
//   §6.5 红线：**模型猜的东西永远不能自动变成约束。**
//
//   本模块的输出**只能决定"问不问"**，绝不允许直接写 knowledge 表。
//   方向上是安全的：模型猜错"该不该问"，代价是少问一次 / 多问一次；
//   而模型猜的**内容**若被写进库，代价是污染识别提示和翻译约束 —— 那正是红线防的事。
//
//   ⚠️ 这个模块**没有任何写知识库的能力**（头文件不 include KnowledgeStore.h），
//   是刻意的结构性保证。以后想给它加写权限的人，请先回 PROJECT.md §6.5 读一遍。
//
// ---------------------------------------------------------------------------
// 【三层判断，从便宜到贵，每一层都能独立失效】
// ---------------------------------------------------------------------------
//   ① 本地通用词表（CommonWords）—— 确定性、离线、零延迟。命中就**不问**。
//   ② 判断缓存（库里存过的判决）—— 离线、零延迟。命中就用缓存的结论。
//   ③ 云端 DeepSeek 判断 —— 覆盖前两层没见过的词。
//   兜底：任何一层失败/缺席 → **默认"问"**（保守）。
//         宁可多问一次，不可因为判断器坏了就**悄悄停止学习** ——
//         后者用户完全看不出来，前者他按个回车就过去了。
//
// ② 的价值不只是省一次调用：**它让判断能力越用越强、对云的依赖越来越低**
//（常见词很快被缓存，之后完全离线可用）。
//
// 【顺序是 ① → ② → ③，这个顺序本身是设计，不是实现细节】
//   确定性的排在最前：本地表的结论不依赖任何外部状态，缓存是"以前的模型判决"。
//   让可能过时的缓存去覆盖本地表的确定结论，等于拿确定性换历史偶然。

namespace triage {

enum class Verdict {
    Ask,    // 值得问用户
    Skip,   // 人人皆知 / 已判定不值得问
};

struct Decision {
    Verdict     verdict = Verdict::Ask;
    std::string source;   // "common_words" | "cache" | "model" | "fallback"
    std::string reason;   // 给人看的理由（进日志与 --gaps 审计）

    // 模型猜的含义 —— **只作为问题的引子，绝不直接写库**。
    //
    // 【它值钱在哪】现在"它指什么"是**开放式**问题，用户要打一整句话。
    // 有了引子就能变成"是指 Compile Once – Run Everywhere 吗？" ——
    // 用户按个 y 或改两个字就行。这一下把开放式问题的成本降到接近选择题，
    // 于是"多问几个"才真的可行（这正是用户否掉"提问稀缺"之后需要的东西）。
    //
    // ⚠️ 猜错的风险由**用户确认**兜住：引子只是问法的一部分，
    // 用户认了才算，不认就自己写。**它永远不会绕过确认进库。**
    // 引子只决定"问法的一部分"，不是知识 —— 用户认了才写库（见 apply_answer）。
    std::string primer;

    // 模型判断的**类型**：person / project / product / term（空 = 模型没给）。
    //
    // 【为什么需要它 —— 抽取器区分不了】
    // 抽取器只有两条路："人名句式 → person"、"其它首字母大写的词 → term"。
    // 所以产品名、项目名一律落进 `term`，于是被问「这是你们项目里的一个重要概念吗」
    // —— 对产品名来说这是明显的错配（用户会觉得系统在胡乱归类）。
    //
    // 而模型**看得到那句话**（"我们在评估 Gecko 这个新方案"），顺手判一个类型
    // 几乎零成本。判出来之后：① 问法按类型变 ② 库里那个标签也跟着改
    //（`KnowledgeStore::set_kind`）。
    //
    // ⚠️ kind 只影响**标签和问法**，不碰 candidate/confirmed —— 判错了代价只是
    // "问法有点怪"，不会污染任何约束（见 set_kind 的说明）。
    std::string kind;
};

// 可注入的判断器 —— 和确认交互的 `LineReader` 同一招。
//
// 【为什么必须可注入】判断一旦联网就不可复现：自检跑不了、行为随模型变。
// 抽成回调之后，自检可以喂**脚本化的判决序列**，走真实的编排逻辑验证结果，
// 而云端实现只是另一个回调。这是 5.2（规划循环）也在用的同一个模式。
//
// 返回 false = 这次判断没成功（网络/超时/解析失败）。
// 调用方**必须**退化成 Vervict::Ask，不许把"判断失败"当成"不值得问"。
using Judge = std::function<bool(const std::string& value,
                                 const std::string& kind,
                                 const std::string& evidence,
                                 Decision* out)>;

// ===========================================================================
// 第 ② 层：判断缓存
// ===========================================================================
//
// 【缓存什么、不缓存什么 —— 这是本层最容易做错的地方】
//
// **只缓存「不问」（Verdict::Skip），并且只缓存模型给出的判决。**
//
// 为什么只缓存 Skip：
//   · 它是**绝大多数**。一场会里首字母大写的词，真正值得问的是少数，
//     剩下每一个都要联网问一次模型 —— 慢、花钱、断网就没法用。
//   · 它是**跨会话重复**的那一类。通用词和话题词在同类内容里反复出现；
//     而值得问的专名一旦问过，库里就有条目了，「问过不再问」由
//     KnowledgeGap 负责 —— 缓存 Ask 等于把同一件事做两遍。
//   · 缓存 Ask 会把**那一刻的引子冻住**。引子是模型猜的，会话内容变多之后
//     本来应该越猜越准；冻住它等于让第一次的瞎猜一直用下去。
//
// 为什么只缓存 source == "model"：
//   · 本地词表的判决是**免费**的（一次查表），缓存它省不下任何东西。
//   · **兜底判决（判断失败）绝对不能缓存** —— 那会把一次网络抖动
//     固化成「这个词永远不问」，而用户完全看不出来。
//     这是本层唯一的严重风险，所以它被结构性排除：
//     `store` 只在 `verdict == Skip && source == "model"` 时被调用，
//     由 decide() 单点守着，调用方**无从绕过**（store 不对外暴露调用时机）。
//
// ⚠️ 缓存的键是**归一化后的词**，不含上下文。所以同一个词在不同语境里角色变了
//    （`pilot` 普通词 → `Pilot` 产品名）会沿用第一次的判决。
//    这是**明知故犯的取舍**：要上下文就得每次都问模型，那缓存就没有意义了。
//    代价由 `--triage-cache --forget <词>` 兜住 —— 宁可留一个明确的手动出口，
//    也不要一个悄悄变复杂、还说不清行为的启发式。
struct CachedVerdict {
    Verdict     verdict = Verdict::Skip;
    std::string kind;      // 模型当时猜的类型（换问法用）
    std::string primer;    // 模型当时猜的含义（做引子用）
    std::string why;       // 模型当时的理由（进审计输出）
    std::string judged_at;
};

// 查缓存。返回 false = 没这个键（**没命中不是错误**，继续往下走）。
// 传进去的是**原样的候选词**，不是归一化键 —— 归一化是缓存层的实现细节，
// 这样本模块（以及自检里的内存缓存）都不需要知道 KnowledgeStore 怎么归一化。
using CacheLookup = std::function<bool(const std::string& value, CachedVerdict* out)>;

// 写缓存。**只会被 decide() 在 Skip + model 时调用**（见上）。
using CacheStore = std::function<void(const std::string& value,
                                      const std::string& kind,
                                      const Decision& d)>;

struct Cache {
    CacheLookup lookup;
    CacheStore  store;

    // 有 lookup 才算"有缓存"。只给 store 不给 lookup 是无意义的组合，
    // 显式当作没有 —— 免得出现"一直在写、从来读不到"这种看起来在工作的假象。
    explicit operator bool() const { return static_cast<bool>(lookup); }
};

// 第 ① 层 + 第 ② 层 + 第 ③ 层的编排。
//
// judge 为空 → 只走第 ①/② 层，其余一律 Ask。
// cache 为空（`Cache{}`）→ 跳过第 ② 层，行为与 2.10 完全一样。
Decision decide(const std::string& value,
                const std::string& kind,
                const std::string& evidence,
                const Judge& judge,
                const Cache& cache = Cache{});

// 云端判断器（DeepSeek）。**需要 API Key；没有 Key 或网络失败时返回 false。**
//
// ⚠️ **本轮未经真实 Key 验证**（开发机上拿不到 Key）。它只做两件事：
//    ① 问模型"这个词是不是人人皆知的通用概念"
//    ② 让它顺便猜一个含义（作为问题引子，让人只需确认或纠正）
// 输出只用于"问 / 不问"和"怎么问"，**不写库**。
Judge make_cloud_judge(const std::string& api_key, int timeout_sec = 12);

}  // namespace triage
