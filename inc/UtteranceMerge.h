#pragma once
#include <string>

// ===========================================================================
// 残句合并（2026-09-19）
// ===========================================================================
//
// 【要解决的问题 —— 用户原话】
//   「感觉翻译没有带着上下文一起理解，只是一句一句的翻译，
//     很多时候被切碎的语句翻译出来就四不像了」
//
// 分句已经改成"按停顿切"（§3.1 主体），但**残句仍然会出现** ——
// 说话人换气、被插话、或者一句话中途停了半秒，都会切出一个残句。
// 而残句被单独送去翻译时，弱模型会**替它补全**，于是产出一句
// 看着通顺、其实原文里没有的话：
//
//     原文 `You get to get in a`   → 「你可以亲自体验一下。」   （下一段才是 car with your family…）
//     原文 `and I'm`               → 译成一句完整的话（见下）
//     原文 `English people actually` → 「实际上，英国人也确实如此。」（English people 被读成"英国人"）
//
// 【为什么"给翻译带上下文"不是解法】
// 试过（`--context`），本地小模型会把**前文也翻译一遍**（已实测），默认已关。
// 所以只能从**时序**上解决：**残句先别译，等下一段到了再决定**。
//
// ---------------------------------------------------------------------------
// 【这个类做什么】
//   · 一段文本"看起来没说完" → 先攒着，不送翻译
//   · 下一段到了：合起来看；仍然没说完就继续攒（有上限）
//   · 攒太久了（说话人停下来了）→ 必须吐出来，不能一直等
//   · 会话结束 → 冲刷（**最容易漏的一条**：漏了就是"最后一句永远不翻译"）
//
// 【为什么时间是参数，不是内部时钟】
// `push(text, now_sec)` / `poll(now_sec)` 里的时间由调用方传。
// 这样整个状态机在自检里可以用**数字驱动**（"3 秒后""10 秒后"），
// 不用真等、也不会 flaky —— 而"等不到下一段"恰恰是这里最容易错的路径，
// 那种路径用真时间测会很脆。
//
// ---------------------------------------------------------------------------
// 【判据刻意保守】
// `looks_incomplete()` 只认**明确的**残句形状（以功能词/代词/数词结尾，
// 且没有终止标点）。判错的代价不对称：
//   · 误判成"没说完" → 只是**晚一拍**出字幕，合并后的文本通常仍然通顺
//   · 漏判（真残句没被认出）→ 回到今天这种"翻译替它补全"的老问题
// ⚠️ 但"合并两句本来无关的话"确实会难看，所以**不用**"没有终止标点"当唯一判据
//    （Whisper 对中文和短句经常完全不打标点，那会合并得太多）。

namespace uttermerge {

// 这段文本看起来"话没说完"吗？（纯函数，可单测）
bool looks_incomplete(const std::string& text);

// 两段文本拼接：中文之间不加空格，其余加一个空格。
std::string join_text(const std::string& a, const std::string& b);

class Joiner {
public:
    // 新的一段识别结果到了。返回**现在就该送去翻译的文本**；空串 = 先攒着。
    //
    // now_sec 是调用方的单调秒数（自检里可以直接给 0/1/2…）。
    std::string push(const std::string& text, double now_sec);

    // 每一轮循环都调一次。攒太久了就吐出来（说话人停下了，等不到下一段）。
    // 返回要翻译的文本，空串 = 继续等。
    std::string poll(double now_sec);

    // 会话结束：把攒着的吐出来。
    // ⚠️ **这一步漏了就是"最后一句永远不翻译"** —— 而它只在收尾路径上发生，
    //    平时跑一百场都看不出来。所以调用点必须显式写，且有自检钉着。
    std::string flush();

    bool holding() const { return !held_.empty(); }
    const std::string& held() const { return held_; }

private:
    std::string held_;
    double      held_at_ = 0.0;
    int         held_count_ = 0;   // 连续攒了几段（防止无限攒下去）
};

// 攒多久必须吐出来（秒）。取 1.5 秒的理由：
// 正常说话的句中停顿在 0.5 秒上下（分句门槛就是 500ms），
// 所以"攒了 1.5 秒还没有下一段"基本可以判定说话人停下来了。
constexpr double kHoldTimeoutSec = 1.5;

// 最多连续攒几段。防止说话人长时间说得断断续续时，字幕一直不出来。
constexpr int kMaxHoldSegments = 3;

}  // namespace uttermerge
