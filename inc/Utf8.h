#pragma once
#include <cstddef>
#include <string>

// UTF-8 净化 —— 交付物与模型输出的最后一道闸
//
// ---------------------------------------------------------------------------
// 为什么需要它（真实数据）
// ---------------------------------------------------------------------------
// 实测：用 `--summarizer local`（混元）生成的 `meeting-42.md` **整体不是合法 UTF-8**：
//
//     ### 询问你\xe7          ← \xe7 是一个没写完的三字节首字节
//     - \x84\xe5\x9b\xbd...   ← 孤立续字节
//
// 【真正的成因 —— 不是模型的锅】
// 是 `LlmSummarizer::parse_reply` 里写了一句 `item.find_first_of(u8"：:")`。
// `find_first_of` **按单字节比较**，而 `u8"："` 是三个字节 `EF BC 9A`，
// 于是它在找「0xEF 或 0xBC 或 0x9A 或 ':'」中的任意**一个字节** ——
// 而 **「的」= `E7 9A 84`，第二个字节就是 `0x9A`**，被当成了冒号：
//
//     item = "询问你的想法：要点"
//     找到的位置 = 「的」中间那个字节（10），真正的冒号在 18
//     substr(0, 10) = "询问你" + `0xE7`   ← 「的」被切成两半
//
// 我一开始把责任归给混元（"翻译模型被逼做结构化输出会吐半个 token"），**那是错的**。
// 对不上账的地方是："净化器报了 6 处坏字节，但摘要那一步一行警告都没有" ——
// 模型回复是干净的，坏字节是**我们自己**产生的。那个 `find_first_of` 已修。
//
// ---------------------------------------------------------------------------
// 那为什么还要留着这道闸
// ---------------------------------------------------------------------------
// 上面那个具体 bug 修了，但**这类事故的入口不止一个**：任何"按字节比多字节分隔符"
// 或"按字节截断"的写法都会产生非法 UTF-8，而且极难在测试里发现
// （自检全绿、文件打开才发现整份乱码）。
// 几百行难易不等的字符串处理里，不能指望每一处都不出错 —— 所以留一道**最后防线**：
// 保证**写出去的文件永远合法**。
//
// ---------------------------------------------------------------------------
// 取向：净化 + **大声报告**，不是拒绝
// ---------------------------------------------------------------------------
// 本项目的规矩是"不支持就报错，绝不静默给错数据"。这里的情况有点特殊：
// 拒绝写盘意味着用户**一份交付物都拿不到**，而那份交付物 99% 的内容是好的。
// 所以选择净化（保证文件永远合法），但**必须打一行警告**把问题暴露出来 ——
// 静默替换才是真正违反那条规矩的做法。
//
// 位置放在**写出边界**（`write_file`）而不是每个字段各自处理：
// 出口只有一个，漏不掉；将来多一种交付物也自动被覆盖。

namespace utf8 {

// 是不是合法 UTF-8。严格判定：拒绝过长编码、拒绝代理对、拒绝越界码点。
bool is_valid(const std::string& s);

// 把非法字节替换成 U+FFFD（EF BF BD），返回净化后的字符串。
// `replaced` 回传替换了几处（每个非法字节算一处）。
//
// 合法输入**原样返回**（逐字节相同），所以可以放心地放在热路径上。
std::string sanitize(const std::string& s, size_t* replaced = nullptr);

}  // namespace utf8
