#pragma once
#include <cstddef>
#include <string>

// UTF-8 净化 —— 交付物与模型输出的最后一道闸
//
// ---------------------------------------------------------------------------
// 为什么需要它（真实数据）
// ---------------------------------------------------------------------------
// 实测：用 `--summarizer local`（混元）生成的 `meeting-42.md` **整体不是合法 UTF-8**：
//
//     ### 询问你\xe7          ← \xe7 是一个没写完的三字节首字节
//     - \x84\xe5\x9b\xbd...   ← 孤立续字节
//
// 【真正的成因 —— 不是模型的锅】
// 是 `LlmSummarizer::parse_reply` 里写了一句 `item.find_first_of(u8"：:")`。
// `find_first_of` **按单字节比较**，而 `u8"："` 是三个字节 `EF BC 9A`，
// 于是它在找「0xEF 或 0xBC 或 0x9A 或 ':'」中的任意**一个字节** ——
// 而 **「的」= `E7 9A 84`，第二个字节就是 `0x9A`**，被当成了冒号：
//
//     item = "询问你的想法：要点"
//     找到的位置 = 「的」中间那个字节（10），真正的冒号在 18
//     substr(0, 10) = "询问你" + `0xE7`   ← 「的」被切成两半
//
// 我一开始把责任归给混元（"翻译模型被逼做结构化输出会吐半个 token"），**那是错的**。
// 对不上账的地方是："净化器报了 6 处坏字节，但摘要那一步一行警告都没有" ——
// 模型回复是干净的，坏字节是**我们自己**产生的。那个 `find_first_of` 已修。
//
// ---------------------------------------------------------------------------
// 那为什么还要留着这道闸
// ---------------------------------------------------------------------------
// 上面那个具体 bug 修了，但**这类事故的入口不止一个**：任何"按字节比多字节分隔符"
// 或"按字节截断"的写法都会产生非法 UTF-8，而且极难在测试里发现
// （自检全绿、文件打开才发现整份乱码）。
// 几百行难易不等的字符串处理里，不能指望每一处都不出错 —— 所以留一道**最后防线**：
// 保证**写出去的文件永远合法**。
//
// ---------------------------------------------------------------------------
// 取向：净化 + **大声报告**，不是拒绝
// ---------------------------------------------------------------------------
// 本项目的规矩是"不支持就报错，绝不静默给错数据"。这里的情况有点特殊：
// 拒绝写盘意味着用户**一份交付物都拿不到**，而那份交付物 99% 的内容是好的。
// 所以选择净化（保证文件永远合法），但**必须打一行警告**把问题暴露出来 ——
// 静默替换才是真正违反那条规矩的做法。
//
// 位置放在**写出边界**（`write_file`）而不是每个字段各自处理：
// 出口只有一个，漏不掉；将来多一种交付物也自动被覆盖。

namespace utf8 {

// 是不是合法 UTF-8。严格判定：拒绝过长编码、拒绝代理对、拒绝越界码点。
bool is_valid(const std::string& s);

// 把非法字节替换成 U+FFFD（EF BF BD），返回净化后的字符串。
// `replaced` 回传替换了几处（每个非法字节算一处）。
//
// 合法输入**原样返回**（逐字节相同），所以可以放心地放在热路径上。
std::string sanitize(const std::string& s, size_t* replaced = nullptr);

// 按**字节上限**截断，但**退到字符边界**，保证结果仍是合法 UTF-8。
// 截断时在末尾追加 marker（默认 "…（已截断）"）。
//
// 【为什么需要它】Agent 的工具结果要进模型上下文，必须限长；
// 而"截断"正是最容易切在字符中间的操作 ——
// 这个项目已经因为按字节切而产出过**整份非法 UTF-8 的交付物**（见本文件开头）。
std::string truncate(const std::string& s, size_t max_bytes,
                     const std::string& marker = "\xE2\x80\xA6\xEF\xBC\x88\xE5\xB7\xB2\xE6\x88\xAA\xE6\x96\xAD\xEF\xBC\x89");

// ---------------------------------------------------------------------------
// UTF-16 → UTF-8：**Windows 命令行参数的正确读法**
// ---------------------------------------------------------------------------
//
// 【为什么必须有它 —— 中文参数会把程序直接搞崩】
// Windows 上 `main(int, char** argv)` 拿到的 argv 是按**当前控制台代码页**
// 编码的。中文 Windows 默认 936（GBK），于是：
//
//     Translator.exe --report "整理过去一周的工作"
//       → argv[2] 是 GBK 字节（`D5 FB C0 ED ...`），不是 UTF-8
//       → 程序当 UTF-8 用 → 非法字节
//       → nlohmann::json::dump() 抛 type_error.316（invalid UTF-8 byte）
//       → 未捕获 → std::terminate → **进程崩溃，exit code 0xC0000409**
//
// 实测就是这样：`--search EnglishPod` 一切正常，`--search 凤凰项目` 崩掉，
// 而且**什么错误都不打**（看起来像"命令没生效"）。
//
// 【为什么不能靠 `chcp 65001`】程序内部确实调了 `chcp 65001`，
// 但那是在**参数已经被编码之后**才执行的；而且实测先在 PowerShell 里
// `chcp 65001` 再跑也无效（PS 5.1 传参用的是自己那套编码）。
//
// 【正确做法】用 `wmain` 拿宽字符参数（Windows 原生就是 UTF-16，
// 与控制台代码页无关），再转成 UTF-8。这样中文参数在**任何**代码页下都对。
std::string from_wide(const wchar_t* w);

// ---------------------------------------------------------------------------
// UTF-8 → UTF-16：**给 std::filesystem / fstream 用的**
// ---------------------------------------------------------------------------
//
// 【为什么必须有它 —— 中文路径会让程序直接崩】
// Windows 上 `std::filesystem::path` 与 `std::ifstream` 从 `std::string`
// 构造时，是按**当前 ANSI 代码页**（中文机器上就是 GBK）解释那段字节的，
// **不是 UTF-8**。于是把 UTF-8 的中文路径交给它们：
//   · 运气好：按 GBK 解出一串乱码 → 文件建到别的地方去了（**静默错**）
//   · 运气不好：那段字节不是合法 GBK → 转换失败 → **抛异常** →
//     没人接住 → `std::terminate` → 进程崩，exit `0xC0000409`
//
// 实测就是崩了：`--new-assistant "英语课助手"` → `0xC0000409`，
// 同一个位置换成 ASCII（`engclass`）完全正常。
//
// ⚠️ 它和 `from_wide` 是**一对**：那次是"宽参数没转成 UTF-8"，
//    这次是"UTF-8 路径没转回宽"。**两个方向都得转**，漏一个就崩。
//
// 用法：`std::ifstream f(std::filesystem::path(utf8::to_wide(p)), ...)`
//      或 `std::ifstream f(utf8::to_wide(p).c_str(), ...)`（MSVC 支持宽路径）
// **不要**再写 `std::ifstream f(utf8_path)`。
//
// ⚠️ **SQLite 不在此列**：`sqlite3_open()` 要的就是 UTF-8，别转。
std::wstring to_wide(const std::string& s);

}  // namespace utf8
