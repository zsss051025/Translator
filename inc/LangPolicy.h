#pragma once
#include <string>

// ===========================================================================
// 源语言策略（2026-09-19 新增）
// ===========================================================================
//
// 【为什么需要它 —— 真实事故】
// 用户真跑一节英文课（`live.db` 会话 #2，3 分钟），其中一段：
//
//     seq=39  conf=0.61  src='春日的留书,你在路上做一回。'
//
// **英文播客里出现了中文原文。** 这不是"Whisper 幻觉出中文"，
// 而是**我们自己让它在那一段重新判语言**：
//
//     const bool do_detect = should_detect_language();   // 首次 + 每 120 秒为真
//     lang_arg = do_detect ? "auto" : current_lang_;     // ← 重检时整段走 auto
//     if (lang_arg == "auto") update_detected_language(); // 判出什么就**切换**成什么
//
// 那一段正好是音乐/转场，Whisper 对**那 3~4 秒**判成了中文 → 吐出中文，
// 然后锁定语言被**切换**成了 zh。
// 时间对得上：#39 在 14:41:27，会话 14:39:08 开始 → 139 秒，正好越过 120 秒的重检点。
//
// ⚠️ 连带风险：锁定变成 zh 而目标语言也是 zh 时，主循环那条
//    「源语言 == 目标语言就跳过翻译」的守卫会触发 —— 后面的英文段会被当成
//    "无需翻译"直接落库。所以"被音乐带偏一次"不只是脏一段，它可能**关掉翻译**。
//
// 【改法】把"一次判断就切换"改成"**连续 N 段一致才切换**"：
//   · 单段判出别的语言 → 只记为**候选**，锁定不变
//   · 候选期间**每段都重新检测**（不是等下一个 120 秒），所以真换了语言
//     也能在 N 段内跟上，不会拖成 N×120 秒
//   · 候选期间只要有一段判回锁定语言（或判成第三种），候选清零
//   · 首次锁定同样要求连续 N 段一致 —— 开场音乐同样可能把语言带偏
//
// 【为什么把这段逻辑从 SpeechEngine 里抽出来】它是个状态机，边界全是
// "第 N 段""候选被谁打断"，而它错了的症状是**静默的语言漂移**（甚至静默关掉翻译）。
// 抽成纯函数之后，自检可以逐条钉住每种转移，不用起引擎、不用真音频。

namespace langpolicy {

// 一次检测的结论
enum class Action {
    None,      // 什么都不做（还在攒候选）
    Lock,      // 首次锁定
    Switch,    // 切换锁定语言（已连续足够多次）
};

// 纯函数状态机：把状态（当前锁定 / 候选 / 候选计数）显式传进传出。
//
//   detected  本次 whisper 判出的语言（如 "en" / "zh"）
//   current   当前锁定语言（空 = 还没锁定）
//   pending   候选语言（空 = 没有候选）—— 会被本函数修改
//   count     候选已连续出现多少次 —— 会被本函数修改
//   need      需要连续多少次才认（>=1；<=1 等于退回"一次就切"）
//
// 返回要执行的动作；调用方负责打日志。**不在这里打日志**，
// 纯函数才能被反复调用而不产生副作用。
Action decide(const std::string& detected,
              const std::string& current,
              std::string* pending,
              int* count,
              int need);

// 候选还在攒的时候，是否应该**每段都重新检测**（而不是等下一个重检周期）。
bool should_probe(const std::string& pending);

}  // namespace langpolicy
