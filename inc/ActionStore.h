#pragma once
#include <functional>
#include <string>
#include <vector>

// ===========================================================================
// 行动项落库 + 跨会话聚合（§7 步骤 5.5）
// ===========================================================================
//
// 【为什么这件事比看上去大】`actions` 表从 2.x 就在 schema 里，但**一行都没写过**：
// 行动项只在生成交付物时在内存里活一次，写进 `actions.csv` 就没了。于是
// "跨会话追踪"（原 2.8）没有任何落点 —— 上周会上说要做的事，这周没人记得，
// 而"记得上周说过什么"恰恰是这产品最该做到的事。
//
// 补上它要回答三个问题，每个都有一个"错了会静默失败"的坑：
//
//   ① **怎么算"同一件事"？** 见下面的判同设计。
//   ② **怎么保证幂等？** 同一场会话重新导出一次交付物就会再 ingest 一次。
//      用计数器的话 seen_count 会凭空涨，而那个数字是要给用户看的
//      （"上周提到过、这周又提了"）—— 于是单开一张
//      `action_sessions` 台账（主键 action_id+session_id），重复 ingest 是
//      INSERT OR IGNORE，天然幂等。
//   ③ **状态由谁改？** todo/doing/done 是**用户的事实**，不是模型的推断。
//      见 set_status 的说明。
//
// ---------------------------------------------------------------------------
// 【判同设计：两层，而且默认「不合并」—— 和分诊层正好相反】
// ---------------------------------------------------------------------------
//   ① 确定性层：`key`（normalize_title 归一化后的标题）完全相同 → 同一件事。
//      这是绝大多数情况（"把接口文档重写了"这周又提一次，归一化后一模一样）。
//   ② 可注入的判同器（模型）：key 不同但标题高度相似（词集重合度过阈值）时才问。
//      和 `triage::Judge` / `agent::Planner` 同一个模式 —— 于是聚合逻辑能进 L1。
//   兜底：判断器缺席或失败 → **当成新任务**（不合并）。
//
// ⚠️ **这里默认"不合并"，而分诊层默认"问" —— 不是前后不一致，是失败面不一样：**
//   · 分诊层判错（该问没问）→ 系统**悄悄停止学习**，用户完全看不出来。所以宁多问。
//   · 聚合层判错（把两件事并成一件）→ 两条真任务变一条，
//     **一条从待办里消失了**，用户同样看不出来。
//   两个默认值都是冲着"别让用户看不见的坏事发生"选的：
//   分诊的可见失败是"多问一次"（他按个回车），聚合的可见失败是"多出一行"（他一眼看到）。
//   换句话说：**两边都选那个"失败时用户看得见"的方向。**

namespace actions {

// 一条行动项
struct Item {
    long long   id = 0;
    std::string key;            // normalize_title(title)
    std::string title;          // 要做的事
    std::string owner;          // 负责人（可能为空）
    std::string due;            // 截止（可能为空）
    std::string status;         // todo | doing | done
    std::string origin;         // summary | agent | user
    std::string evidence;       // 来源原话
    long long   source_session = 0;
    int         source_seq = 0;
    double      confidence = -1.0;
    std::string created_at, updated_at;

    // 派生（来自 action_sessions 台账，不是表里的列）——
    // 【为什么派生而不是存列】存列就会和台账漂移，而漂移之后
    // "在 3 场会话里被提到"就变成一句没人能验证的话。
    int         seen_sessions = 0;      // 在几场会话里出现过
    long long   last_session = 0;       // 最近一次是哪一场
};

// 写进来的东西。**刻意不直接用 DeliverableWriter 的 ActionItem** ——
// 那样这个存储层就反过来依赖上层（产出器），单向分层就破了。
// 而且抽出这个结构之后，摘要器和 agent 的 propose_action
// 走的是**同一个入口**（两处各写一份写入逻辑是这个项目明确禁止的事）。
struct Incoming {
    std::string title;
    std::string owner;
    std::string due;
    std::string evidence;
    int         source_seq = 0;
};

// 标题归一化：判"是不是同一件事"的键。
//
// 做四件事：转小写、把标点换成空格、压掉多余空白、去掉首尾空白。
// **不做**词形还原/同义替换 —— 那是判同器（模型）该干的，
// 塞进这里会让"为什么这两条被合并了"变得没法解释。
std::string normalize_title(const std::string& raw);

// 两条标题里**连续相同的最长片段**有多少个字符（按 UTF-8 字符数算）。
// 剥掉空白之后再比 —— 否则"重写 这块"和"重写这块"会看不出相同。
size_t longest_shared_run(const std::string& a, const std::string& b);

// 是否存在一段**长度 ≥ min_len、而且在两边都正好落在一个分句结尾**的相同片段。
//
// 【为什么需要"落在分句结尾"这个额外条件 —— 这是被自检逼出来的】
// 最初只用"连续相同 ≥ 8 字"，自检立刻报了一条**真错**：
//     「凤凰项目的接口文档需要重写。」  vs  「凤凰项目的接口文档需要评审。」
// 这两条是**两件事**（一个要写、一个要评），可它们有 11 个字完全相同，
// 于是被判成了同一件事 —— 也就是"一条真待办从列表里消失了"，
// 正是我在头文件里说要避免的那种静默损失。
//
// 区别在哪？看相同片段**在哪里断的**：
//     #1/#4  「…接口文档需要重写，」+ 各自不同的后续分句
//            → 相同的那段本身是**一个完整分句**（后面跟着逗号）
//     A/B    「…接口文档需要 | 重写」 / 「… | 评审」
//            → 相同的那段在**分句中间**断掉，差异恰好在分句的谓语上
// 人在判断"是不是同一件事"时用的就是这个：**差异落在主干上（谓语）不是补充说明，
// 就是两件事。** 所以要求相同片段在两边都以分句边界收尾。
//
// ⚠️ **已知的漏判**（这是刻意选的方向）：换了个说法的同一件事，例如
//      「另外李经理需要提交一份极光平台的压测报告。」
//      「李经理需要提交一份压测报告，负责极光平台那部分。」
//   相同片段「李经理需要提交一份」在两边都不是分句结尾 → **不会自动合并**。
//   它会留在待办列表里显示成两条。这是**故意选的失败方向**：
//   不合并的代价是"多一行、用户看得见"，错合并的代价是"一条真待办静默消失"。
//   这一档交给可注入的判断器（模型）—— 那才是它能可靠判断的事。
bool has_boundary_aligned_shared_run(const std::string& a, const std::string& b,
                                     size_t min_len);

// 纯函数：可判定的"同一件事"。两层，都是确定性的：
//   ① 归一化标题完全相同
//   ② 有足够长的连续相同片段（见 kMinSharedRun 的说明）
bool same_thing(const Item& a, const Item& b);

// 纯函数：标题相似度（词集重合，0~1）。用于决定"要不要问判断器"。
double title_similarity(const std::string& a, const std::string& b);

// 判"同一件事"的第二层：**连续相同片段 ≥ 这个字数**就算同一件事。
//
// 【为什么需要这一层 —— 只有①根本不够用】
// 规则抽取器给出的任务文本是**整个句子**，不是提炼过的待办标题：
//     第一场：「凤凰项目的接口文档需要重写，这块张伟负责跟进。」
//     第二场：「凤凰项目的接口文档需要重写，这个上周就说了，张伟负责跟进，这周五之前完成。」
// 这两条是**同一件事**，但归一化后一个是 22 字、一个是 34 字，key 不可能相同。
// 实测就是这样：第一版只有规则①，三场会最后攒出 8 条重复任务，
// 「跨会话聚合」一个字都没生效 —— 也就是说 5.5 的核心功能是假的。
//
// 【为什么是"连续相同片段"而不是"相似度阈值"】
// 相似度是个加权平均数，**它分不清"同一个任务多说了一句"和"两个不同任务用词相近"**：
//     「接口文档需要重写」 vs 「接口文档需要评审」 相似度极高，但是两件事
// 而"连续 8 个字一模一样"这个条件，前者成立、后者不成立 —— 它抓的是
// **任务描述里那段没被改写的主干**，这正是人判断"是不是同一件事"时用的东西。
//
// 【8 是怎么定的】中文里"安全评审"（4 字）、"接口文档"（4 字）这类短语太短，
// 两件不相干的事也可能撞上；而 8 字连读相同，基本只剩"同一句话没改"或
// "同一个任务换了补充说明"两种可能。**英文单独处理**：8 个字母太弱
// （"deadline" 就 8 个），所以英文走"实词重合 + 至少 3 个共同实词"。
constexpr size_t kMinSharedRun = 8;

// 超过这个相似度才值得问判断器。太低就是给模型发一堆不相干的配对。
constexpr double kAskJudgeAbove = 0.45;

// 可注入的判同器。返回 true = 认为 incoming 和 existing 是同一件事。
// **不返回"失败"**：判不出来就返回 false（= 当新任务），
// 因为"合并"是有损的、且失败不可见。
using SameJudge = std::function<bool(const Item& existing, const Item& incoming)>;

struct Outcome {
    int         inserted = 0;   // 新建了几条
    int         merged   = 0;   // 判为同一件事、并入已有条目的几条
    int         linked   = 0;   // 台帐里新增的记录数（幂等：重复 ingest 会是 0）
    int         judged   = 0;   // 问了几次判断器（用于说明"花了多少代价"）
    std::string err;
};

// 落库 + 跨会话聚合。**幂等**。
//
// session_id 用来记账（这个任务出现在哪几场）。已存在的条目会：
//   · 台账插一条 (action_id, session_id) —— 已经有了就跳过
//   · 空字段才被填入（owner/due 本来有值就不覆盖，理由见 .cpp）
//   · **status 一个字都不动** —— 用户标了 done 的任务
//   不会因为下周的会上又提了一次就被打回 todo
//
// ---------------------------------------------------------------------------
// 【为什么这部分是 class 的静态函数，而上面那些判同函数是自由的】
// 因为**要不要数据库**是个应该从 API 上看得出来的区别：
//   · `normalize_title` / `title_similarity` / `same_thing` —— 纯函数，
//     自检可以不建库直接喂数据验它们（判同逻辑是最容易错、最该单独验的部分）。
//   · 下面这几个必须碰 `SessionStore` 的连接。而那个连接是**私有**的，
//     只对 `friend class` 开放 —— 命名空间里的自由函数拿不到它。
// 所以这个划分不是风格问题：**它让"哪些函数需要真库"变成一眼可见的事实**，
// 也让自检里判同那部分完全不需要准备数据库。
// （`DeliverableWriter` 也是 class + static 的写法，同一个道理。）
class ActionStore {
public:
    static Outcome ingest(long long session_id, const std::vector<Incoming>& items,
                          const SameJudge& judge = nullptr,
                          const std::string& origin = "summary",
                          double confidence = -1.0);

    // 查询。status 为空 = 全部。按 status 排序（todo 在前）、再按最近出现倒序。
    static std::vector<Item> list(const std::string& status = "", int limit = 200);

    // 某场会话里的行动项（用于"这场会定了哪些事"）
    static std::vector<Item> for_session(long long session_id);

    static bool get(long long id, Item* out);

    // 状态流转。**这是用户的操作，不是模型能做的事。**
    //
    // 【为什么 agent 不拿这个工具】"这件事做完了吗"是**只有用户知道的事实**。
    // 模型从"我把接口文档改好了"这句话推断出 done，看起来合理 ——
    // 但代价是那条任务**从待办列表里消失了**，而用户没看见它消失。
    // 这和 §6.5 红线是同一个道理（模型猜的东西不能静默变成事实），
    // 只是后果从"污染识别提示"换成了"你的待办少了一条"。
    // 所以状态只由 `--actions --done <id>` 这类显式命令改。
    static bool set_status(long long id, const std::string& status,
                           std::string* err = nullptr);

    // 只读统计（给 `--actions` 和演示脚本看）
    struct Stats { int todo = 0, doing = 0, done = 0, total = 0; };
    static Stats stats();
};

const std::vector<std::string>& valid_statuses();

}  // namespace actions
