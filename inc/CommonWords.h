#pragma once
#include <string>

// ===========================================================================
// "通用概念"过滤表 —— 决定**哪些东西不该问用户**
// ===========================================================================
//
// 【它是什么，以及它不是什么】
// 用户提的需求是"有一个基础知识库，遇到只会在我会话里出现的名词才问"。
// 但真正需要的**不是**一个"能回答 TV 是什么"的库 —— 模型本来就知道 TV 是电视，
// 建这个库是白费力气。需要的是让系统知道：
//
//     **这件事人人皆知，问了只是浪费用户的注意力。**
//
// 所以这个模块是一份**否决清单**，不是一份知识。它的产物是一句话：
// "别问这个。"
//
// ---------------------------------------------------------------------------
// 【它和 is_never_name 的区别 —— 两者不能合并】
// ---------------------------------------------------------------------------
//   `KnowledgeExtract::is_never_name`  提取阶段的**判定**表：
//        "这不可能是个专名"（功能词、问候语、语气词）。
//        放错一个词的代价是**漏掉一个真专名** → 宁缺勿滥，只收铁定的。
//   本表                              提问阶段的**过滤**表：
//        "这就算是专名，也不值得问"。
//        放错一个词的代价是**少问一次** → 可以宽，而且越宽越省用户的事。
//
// 两个阶段的目标相反，所以必须是两张表。合并会导致其中一个目标被牺牲。
//
// ---------------------------------------------------------------------------
// 【表里的词从哪来 —— 不是我拍脑袋想的】
// ---------------------------------------------------------------------------
// 每一条都来自**真实会话里被抽出来、并且真的问过用户**的词：
//
//   会话 #12（66 段英语播客）  froze / people / action / PC / learners
//   会话 #13（117 段播客）     putting / together（全大写小标题里出来的）
//   会话 #46                   Preview / Learners / Exactly
//   会话 #47（53 段播客）      down / Keep / movies / Speaking / Midnight
//   用户三场演示（demo.db）     TV
//
// 也就是说：**这些都是实际发生过的冤枉提问**，用户为此付出过注意力。
// 通用缩写那一类是同理的直接推广（API / CPU / KPI 这种，没人需要被问）。
//
// 【已知的取舍】如果某个项目恰好把一个通用词当自己的专名（比如产品就叫
// "Preview"），它会**永远不会被问**。这是有意的 —— §1.3「提问是稀缺资源」，
// 少问一次的代价远小于问一个蠢问题（那会让用户第三次使用就不看了）。
// 真需要的话，用户可以在会话里明说，或者走 `--glossary` 显式喂进去。
namespace commonwords {

// 这个键（归一化后的小写形式）是人人都懂的通用概念吗？
// true = 不要拿它去问用户。
bool is_general(const std::string& key);

// 表里有多少条（自检与日志用；"手写计数会撒谎"那一课之后，
// 这里给的是**真实值**，不是写死的数字）。
size_t size();

}  // namespace commonwords
