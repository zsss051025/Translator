#pragma once
#include <string>
#include <vector>

// ===========================================================================
// 识别结果的垃圾过滤（幻觉 / 非内容）
// ===========================================================================
//
// 【为什么需要独立一份，而不是继续写在 SpeechEngine 里】
// 这些判据**必须有单测**，而它们的失败方式是"悄悄少了一句人话"或
// "悄悄多了一句假话"，两种都不会报错。放在 SpeechEngine.cpp 的匿名 namespace 里
// 就没法直接测（要起引擎、加载模型、喂音频）。
//
// 抽出来之后，自检可以拿**真实会话里抓到的原句**直接断言 —— 下面那些
// 黑名单词就是从真实数据里来的，不是猜的。

namespace speechfilter {

// 归一化：只保留字母数字与多字节字符，去掉空白标点并转小写。
// 用于黑名单匹配、术语提示回显判断、跨段重复判断 —— **三种判据共用这一份**。
// （以前它只服务后两种；黑名单如果自己再写一个小写化，两边判重标准迟早不一致。）
std::string normalize_for_compare(const std::string& s);

// 这段文本里**一个"内容字符"都没有**吗？
//
// 内容字符 = ASCII 字母数字，或任何首字节 >= 0xC3 的多字节字符
// （带音标的拉丁字母 / 希腊 / 西里尔 / 汉字 / 假名 / 韩文…）。
//
// 【为什么按首字节就能判】U+0080~U+00BF 这一段（`¶` `·` `°` `«` `»` `¿` `¡`）
// 的 UTF-8 首字节全是 0xC2，而它们**都是符号不是字母**；
// 真正带音标的拉丁字母从 U+00C0（`À`）起，首字节 0xC3。
// 所以"首字节 >= 0xC3"就等于"这是个字"，不需要解出码点。
//
// 【为什么必须有这条】真实会话（2026-09-19，126 段）里有 5 段是 ` ¶¶`、
// 1 段是 ` ...` —— Whisper 在纯音乐/静音上吐出的东西。
// 它们**全部通过了置信度检查**（0.70~0.79），而且**每一段都被送去翻译了一次**，
// 最后原样出现在交付物的双语全文里。
bool has_no_content(const std::string& s);

// 是不是 Whisper 的"套话幻觉"？
//
// 【为什么阈值挡不住，只能上黑名单 —— 有实测证据】
// 同一次真实会话里：
//     seq 97/106/119  ` Sous-titrage Société Radio-Canada`   conf 0.75~0.81
//     seq  39…46      ` ¶¶`                                  conf 0.70~0.79
// 全是**高置信度**输出。原因很直接：这类句子在训练数据里和"字幕/音乐"
// 这个上下文绑得极紧，模型对它"很有把握"。所以模型自报的
// `no_speech_prob` 和平均 token 概率在这里**系统性失效** ——
// 一个"确信自己在说实话"的幻觉，只能靠"这句话本身是不是内容"来判。
//
// 【判据刻意保守】只收**整类不变**的套话：各家字幕组/平台的署名、推广语。
// 它们在真实讲话里基本不会出现（会说"sous-titrage"的会议本身就在做字幕，
// 而那也认了）。统计类判据（重复、低置信度）在别处另有实现，不在这里重复。
//
// ⚠️ 方向：**宁可漏掉一条幻觉，也不要把人真说的话删掉**。
//    漏掉的幻觉用户看得见（读着别扭）；删掉的真话用户看不见（他以为录丢了）。
bool is_boilerplate_hallucination(const std::string& raw);

// 黑名单本身（给自检和排查用，会做归一化）
const std::vector<std::string>& boilerplate_patterns();

}  // namespace speechfilter
